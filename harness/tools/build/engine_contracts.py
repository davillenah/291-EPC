#!/usr/bin/env python3
"""Engine contracts written from the schemas, never by hand (GEN-09).

  python harness/tools/build/engine_contracts.py           (re)write harness/docs/ENGINE_CONTRACTS.md
  python harness/tools/build/engine_contracts.py --check   fail when the file differs from what the schemas give

Every engine that has `src/<package>/schema/input.schema.json` (and `output.schema.json`) gets a section: one table per schema with each field
(dotted path, `[]` for the items of a list), its type, whether it is required and its limits. Engines without a schema are listed at the end, so
the gap is visible (OPT-09 adds them). Standard library only.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
ENGINES = REPO / "harness" / "src" / "engines"
OUT = REPO / "harness" / "docs" / "ENGINE_CONTRACTS.md"
LIMITS = ("minimum", "exclusiveMinimum", "maximum", "exclusiveMaximum", "minItems", "maxItems", "minLength", "pattern")


def engines():
    """[(engine folder name, package folder)] of every engine package, sorted."""
    found = []
    for project in sorted(ENGINES.glob("*/*/pyproject.toml")):
        for pkg in sorted((project.parent / "src").glob("epc_*")):
            if pkg.is_dir():
                found.append((project.parent.name, pkg))
    return found


def kind(node):
    if "enum" in node:
        return "one of " + ", ".join(f"`{v}`" for v in node["enum"])
    if "const" in node:
        return f"`{node['const']}`"
    t = node.get("type", "any")
    t = " or ".join(t) if isinstance(t, list) else t
    if "$ref" in node:
        t = "see " + node["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in node or "oneOf" in node:
        t = " or ".join(kind(x) for x in node.get("anyOf", node.get("oneOf", [])))
    return t


def limits(node):
    return ", ".join(f"{k} {node[k]}" for k in LIMITS if k in node)


def row(node, path, required):
    return (path, kind(node), "yes" if required else "", limits(node), node.get("description") or "")


def children(node, path):
    """(child node, its dotted path, required) of an object's properties and of the properties of a list's items."""
    found = [(sub, f"{path}.{name}" if path else name, name in set(node.get("required", []))) for name, sub in node.get("properties", {}).items()]
    items = node.get("items") if node.get("type") == "array" else None
    if isinstance(items, dict):
        need = set(items.get("required", []))
        found += [(sub, f"{path}[].{name}", name in need) for name, sub in items.get("properties", {}).items()]
    return found


def rows(node, path="", required=True):
    out = [row(node, path, required)] if path else []
    for sub, sub_path, need in children(node, path):
        out += rows(sub, sub_path, need)
    return out


def table(schema):
    lines = ["| Field | Type | Required | Limits | Notes |", "|---|---|---|---|---|"]
    cell = lambda v: str(v).replace("|", "\\|")                         # a pipe inside a pattern would split the cell
    lines += [f"| `{cell(p)}` | {cell(t)} | {r} | {cell(l)} | {cell(d)} |" for p, t, r, l, d in rows(schema)]
    return lines


def render():
    out = ["# Engine contracts", "", "Generated by `python harness/tools/build/engine_contracts.py` from each engine's `schema/input.schema.json` and "
           "`schema/output.schema.json`; do not edit by hand (GEN-09).", ""]
    missing = []
    for name, pkg in engines():
        schemas = [(side, pkg / "schema" / f"{side}.schema.json") for side in ("input", "output")]
        present = [(side, p) for side, p in schemas if p.is_file()]
        if not present:
            missing.append(pkg.name)
            continue
        out += [f"## {pkg.name}", ""]
        for side, p in present:
            schema = json.loads(p.read_text(encoding="utf-8"))
            out += [f"### {side.capitalize()}", "", f"Schema: `{p.relative_to(REPO).as_posix()}`" + (f" ({schema['title']})" if schema.get("title") else ""), ""]
            out += table(schema) + [""]
    out += ["## Engines without a schema contract", "", "These engines do not yet validate their input against a schema at the entry point (OPT-09):", ""]
    out += [f"- `{m}`" for m in missing] + [""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python harness/tools/build/engine_contracts.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
