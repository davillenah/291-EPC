#!/usr/bin/env python3
"""The error catalogue, written from the engines' own message tables, never by hand (GEN-08, ADR-0039).

  python harness/tools/build/error_catalogue.py           (re)write harness/docs/ERROR_CATALOGUE.md
  python harness/tools/build/error_catalogue.py --check   fail when the file differs from what the engines give

Every engine that has `src/<package>/messages.py` with a `MESSAGES` dict (`code -> {"en": ..., "es": ...}`) gets a section: one row per code with its English and
Spanish text. Codes that start with `err_` are errors (raised); the others are warnings or labels the engine puts in its result. The tool reads the
`messages.py` files as text with `ast`, so no engine has to be importable. Standard library only.
"""
import argparse
import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
ENGINES = REPO / "harness" / "src" / "engines"
OUT = REPO / "harness" / "docs" / "ERROR_CATALOGUE.md"


def message_files():
    """[(package name, path of its messages.py)] sorted by package."""
    return sorted((p.parent.name, p) for p in ENGINES.glob("*/*/src/epc_*/messages.py"))


def read_messages(path):
    """The `MESSAGES` dict of a messages.py as `{code: {"en": text, "es": text}}`; a non-literal table is an error here, not a silent gap."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        target = node.target if isinstance(node, ast.AnnAssign) else (node.targets[0] if isinstance(node, ast.Assign) else None)
        if isinstance(target, ast.Name) and target.id == "MESSAGES":
            return ast.literal_eval(node.value)
    raise ValueError(f"{path}: no MESSAGES dict")


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render():
    out = ["# Error catalogue", "", "Generated by `python harness/tools/build/error_catalogue.py` from each engine's `messages.py`; do not edit by hand (GEN-08, ADR-0039).", "",
           "A code is stable: its text may be reworded, the code is never reused for another meaning. `err_*` codes are raised by the engine (`<Engine>Error`, with `code`, `en` and `es`); "
           "the other codes are warnings and labels the engine puts in its result. `{name}` is filled in from the call.", ""]
    files = [(package, read_messages(path)) for package, path in message_files()]
    out += [f"{sum(len(m) for _, m in files)} codes in {len(files)} engines.", ""]
    for package, messages in files:
        errors = sum(1 for c in messages if c.startswith("err_"))
        out += [f"## {package}", "", f"{len(messages)} codes ({errors} errors).", "", "| Code | English | Español |", "|---|---|---|"]
        out += [f"| `{code}` | {cell(m['en'])} | {cell(m['es'])} |" for code, m in sorted(messages.items())] + [""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python harness/tools/build/error_catalogue.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
